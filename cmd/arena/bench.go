func cmdBench(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("bench", flag.ExitOnError)
	rtName := fs.String("runtime", "docker", "runtime")
	envDir := fs.String("envs", "environments", "environments directory")
	dataDir := fs.String("data", "data/bench", "data directory")
	levels := fs.String("concurrency", "1,8,32", "concurrency levels for throughput")
	resets := fs.Int("resets", 30, "samples per reset-latency series")
	out := fs.String("out", "bench/RESULTS.md", "results file")
	verbose := fs.Bool("v", false, "verbose logs")
	_ = fs.Parse(args)

	log := newLogger(*verbose)
	r, closeRT, err := openRuntime(ctx, *rtName, log)
	if err != nil {
		return err
	}
	defer closeRT()
	task, err := loadTask(*envDir, "fix-the-bug", "median")
	if err != nil {
		return err
	}
	var md strings.Builder
	fmt.Fprintf(&md, "# Benchmarks\n\nGenerated by `arena bench` on %s.\n\n", time.Now().UTC().Format("2006-01-02 15:04 UTC"))
	md.WriteString(machineInfo(*rtName))

	// 1. Reset latency, cold vs warm.
	fmt.Fprintln(os.Stderr, "reset latency (cold)...")
	cold, err := resetSeries(ctx, r, task, *dataDir, *resets, false)
	if err != nil {
		return err
	}
	fmt.Fprintln(os.Stderr, "reset latency (warm)...")
	warm, err := resetSeries(ctx, r, task, *dataDir, *resets, true)
	if err != nil {
		return err
	}
	md.WriteString("## Reset latency (`fix-the-bug`, PROVISION + SETUP, host-measured)\n\n")
	md.WriteString("Time from `Start()` to the first observation: sandbox acquisition + copying task files + setup steps. ")
	md.WriteString("Cold creates and starts a container; warm takes a pre-started one from the pool (refilled in the background between samples).\n\n")
	md.WriteString("| Pool | n | p50 | p95 | p99 | mean |\n|---|---|---|---|---|---|\n")
	for _, s := range []struct {
		name string
		ds   []time.Duration
	}{{"cold", cold}, {"warm", warm}} {
		fmt.Fprintf(&md, "| %s | %d | %s | %s | %s | %s |\n", s.name, len(s.ds), p(s.ds, 50), p(s.ds, 95), p(s.ds, 99), avg(s.ds))
	}

	// 2. Throughput + phase overheads.
	md.WriteString("\n## Throughput (`fix-the-bug`, honest agent, full episodes incl. grading)\n\n")
	md.WriteString("Warm pool size = concurrency. Every episode creates two sandboxes (student, then grader).\n\n")
	md.WriteString("| Concurrency | Episodes | Wall | Episodes/sec | Mean reward | Infra failures | Reset p50 | Reset p95 | Custody p50 | Grade p50 |\n|---|---|---|---|---|---|---|---|---|---|\n")
	var phaseRows []string
	for _, ls := range strings.Split(*levels, ",") {
		c, err := strconv.Atoi(strings.TrimSpace(ls))
		if err != nil || c < 1 {
			return fmt.Errorf("bad concurrency %q", ls)
		}
		n := max(8, 2*c)
		fmt.Fprintf(os.Stderr, "throughput at concurrency %d (%d episodes)...\n", c, n)
		res, err := throughput(ctx, r, task, *dataDir, c, n)
		if err != nil {
			return err
		}
		fmt.Fprintf(&md, "| %d | %d | %s | %.2f | %.3f | %d | %s | %s | %s | %s |\n", c, n, res.wall.Round(time.Millisecond),
			float64(n)/res.wall.Seconds(), res.meanReward, res.infra,
			p(res.reset, 50), p(res.reset, 95), p(res.custody, 50), p(res.grade, 50))
		if c == 1 {
			phaseRows = append(phaseRows,
				fmt.Sprintf("| CUSTODY (kill+verify, prescan, copy-out, validate, artifact, destroy) | %s | %s | %s |", p(res.custody, 50), p(res.custody, 95), p(res.custody, 99)),
				fmt.Sprintf("| GRADE (fresh sandbox, copy hidden + submission, run grader, destroy) | %s | %s | %s |", p(res.grade, 50), p(res.grade, 95), p(res.grade, 99)),
				fmt.Sprintf("| STUDENT_TURN (honest agent: 5 tool calls) | %s | %s | %s |", p(res.turn, 50), p(res.turn, 95), p(res.turn, 99)))
		}
	}
	if len(phaseRows) > 0 {
		md.WriteString("\n## Custody + grade overhead (concurrency 1)\n\n| Phase | p50 | p95 | p99 |\n|---|---|---|---|\n")
		md.WriteString(strings.Join(phaseRows, "\n") + "\n")
		md.WriteString("\nGRADE includes creating (or taking warm) the grader sandbox, copying hidden files and the custody copy in, locking permissions, and the `fix-the-bug` grader starting one Python subprocess per hidden case (10 cases) as an unprivileged uid, so submitted code never runs in the grader's own process. Using the stock `python:3.12-alpine` image (no `.pyc` files, read-only root) GRADE was 3.1 s at p50; precompiling the stdlib in `images/python` brought it to ~1.2 s.\n")
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		return err
	}
	fmt.Print(md.String())
	return os.WriteFile(*out, []byte(md.String()), 0o644)
}

func benchCfg(r rt.Runtime, dataDir string) episode.Config {
	return episode.Config{Runtime: r, ArtifactDir: filepath.Join(dataDir, "artifacts"), Logger: newLogger(false)}
}

// resetSeries measures Start() latency n times.
func resetSeries(ctx context.Context, r rt.Runtime, task *env.Task, dataDir string, n int, warm bool) ([]time.Duration, error) {
	size := 0
	if warm {
		size = 2
	}
	pool := scheduler.NewPool(r, scheduler.PoolConfig{Size: size, Logger: newLogger(false)})
	defer pool.Close(context.Background())
	cfg := benchCfg(pool, dataDir)
	if warm {
		pool.Warm(task.Env().StudentSpec())
	}
	var out []time.Duration
	for i := 0; i < n; i++ {
		if warm {
			deadline := time.Now().Add(time.Minute)
			for pool.Idle() < size && time.Now().Before(deadline) {
				time.Sleep(20 * time.Millisecond)
			}
		}
		ep := episode.New(cfg, task, fmt.Sprintf("bench-reset-%v-%d", warm, i), 1)
		start := time.Now()
		_, err := ep.Start(ctx)
		d := time.Since(start)
		ep.Close(ctx)
		if err != nil {
			return nil, fmt.Errorf("reset sample %d: %w", i, err)
		}
		out = append(out, d)
	}
	return out, nil
}

type tput struct {
	wall                        time.Duration
	meanReward                  float64
	infra                       int
	reset, custody, grade, turn []time.Duration
}

func throughput(ctx context.Context, r rt.Runtime, task *env.Task, dataDir string, c, n int) (tput, error) {
	pool := scheduler.NewPool(r, scheduler.PoolConfig{Size: c, Logger: newLogger(false)})
	defer pool.Close(context.Background())
	pool.Warm(task.Env().StudentSpec())
	pool.Warm(task.Env().GraderSpec())
	deadline := time.Now().Add(2 * time.Minute)
	for pool.Idle() < 2*c && time.Now().Before(deadline) {
		time.Sleep(50 * time.Millisecond)
	}
	s := scheduler.New(scheduler.Config{Concurrency: c, QueueSize: n, Episode: benchCfg(pool, dataDir), Metrics: metrics.New(), Logger: newLogger(false)})
	newPolicy := func() episode.Policy { p, _ := agent.Honest("fix-the-bug", "median"); return p }
	start := time.Now()
	var chans []<-chan scheduler.Result
	for i := 0; i < n; i++ {
		ch, err := s.Submit(scheduler.Job{ID: fmt.Sprintf("bench-c%d-%d-%d", c, start.Unix(), i), Task: task, Agent: "honest", NewPolicy: newPolicy})
		if err != nil {
			return tput{}, err
		}
		chans = append(chans, ch)
	}
	var res tput
	sum := 0.0
	for _, ch := range chans {
		rr := <-ch
		o := rr.Outcome
		if o == nil || o.Status != episode.StatusDone {
			res.infra++
			continue
		}
		sum += o.Reward
		res.reset = append(res.reset, o.Phases[episode.Provision]+o.Phases[episode.Setup])
		res.custody = append(res.custody, o.Phases[episode.Custody])
		res.grade = append(res.grade, o.Phases[episode.Grade])
		res.turn = append(res.turn, o.Phases[episode.StudentTurn])
	}
	res.wall = time.Since(start)
	if done := n - res.infra; done > 0 {
		res.meanReward = sum / float64(done)
	}
	return res, s.Shutdown(ctx)
}

func p(ds []time.Duration, q float64) string {
	if len(ds) == 0 {
		return "-"
	}
	c := append([]time.Duration(nil), ds...)
	sort.Slice(c, func(i, j int) bool { return c[i] < c[j] })
	idx := int(float64(len(c)-1)*q/100 + 0.5)
	return fmtDur(c[idx])
}

func avg(ds []time.Duration) string {
	if len(ds) == 0 {
		return "-"
	}
	var s time.Duration
	for _, d := range ds {
		s += d
	}
	return fmtDur(s / time.Duration(len(ds)))
}

func fmtDur(d time.Duration) string {
	if d < time.Second {
		return fmt.Sprintf("%d ms", d.Milliseconds())
	}
	return fmt.Sprintf("%.2f s", d.Seconds())
}

func machineInfo(rtName string) string {
	cpu := "unknown"
	if b, err := os.ReadFile("/proc/cpuinfo"); err == nil {
		for _, l := range strings.Split(string(b), "\n") {
			if strings.HasPrefix(l, "model name") {
				cpu = strings.TrimSpace(strings.SplitN(l, ":", 2)[1])
				break
			}
		}
	}
	mem := "unknown"
	if b, err := os.ReadFile("/proc/meminfo"); err == nil {
		f := strings.Fields(strings.SplitN(string(b), "\n", 2)[0])
		if len(f) >= 2 {
			kb, _ := strconv.Atoi(f[1])
			mem = fmt.Sprintf("%.1f GiB", float64(kb)/(1<<20))
		}
	}
	kernel, _ := exec.Command("uname", "-r").Output()
	dockerV, _ := exec.Command("docker", "version", "--format", "{{.Server.Version}}").Output()
	return fmt.Sprintf("| Machine | |\n|---|---|\n| CPU | %s × %d vCPU |\n| Memory | %s |\n| Kernel | %s |\n| Runtime | %s (Docker %s, cgroup v1, runc) |\n| Go | %s |\n| Sandbox limits | 1 CPU, 256 MiB, 64 PIDs, 32 MiB tmpfs per sandbox |\n\n",
		cpu, runtime.NumCPU(), mem, strings.TrimSpace(string(kernel)), rtName, strings.TrimSpace(string(dockerV)), runtime.Version())
}
